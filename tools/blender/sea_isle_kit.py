def noise(x, z, seed=0.0):
    """Smooth noise from a few rotated sine layers (no numpy needed), about -1..1."""
    v = 0.0
    amp = 1.0
    f = 0.035
    for k in range(5):
        a = 1.3 * k + seed
        u = x * math.cos(a) - z * math.sin(a)
        w = x * math.sin(a) + z * math.cos(a)
        v += amp * (math.sin(u * f + 1.7 * k + seed) * math.cos(w * f * 1.3 + 0.9 * k))
        amp *= 0.5
        f *= 2.03
    return v / 1.94


def smooth(a, b, x):
    t = max(0.0, min(1.0, (x - a) / (b - a) if b != a else 0.0))
    return t * t * (3 - 2 * t)


def slope(land, x, z, e=1.0):
    hx = land(x + e, z) - land(x - e, z)
    hz = land(x, z + e) - land(x, z - e)
    return math.hypot(hx, hz) / (2 * e)


def ground(name, land, reach, cells, trodden=None, forest=None, chunks=1):
    """land(x, z) -> metres above sea level (island-local, x east, z south). trodden(x, z) -> 0..1 path weight,
    forest(x, z) -> 0..1 forest-floor weight (vertex alpha). chunks: the mesh is cut into chunks x chunks pieces (each
    culled and given its own detail levels by the game); normals come from the height function so the cuts never show.
    Returns the list of objects."""
    step = 2.0 * reach / cells
    def normal(x, z):
        e = step * 0.5
        dx = (land(x + e, z) - land(x - e, z)) / (2 * e)
        dz = (land(x, z + e) - land(x, z - e)) / (2 * e)
        n = (-dx, dz, 1.0)  # Blender order (x, forward = -z, up)
        ln = math.sqrt(n[0] ** 2 + n[1] ** 2 + 1.0)
        return (n[0] / ln, n[1] / ln, n[2] / ln)
    per = cells // chunks
    objs = []
    for ci in range(chunks):
        for cj in range(chunks):
            bm = bmesh.new()
            verts = {}
            norms = {}
            for i in range(ci * per, min(cells, (ci + 1) * per) + 1):
                for j in range(cj * per, min(cells, (cj + 1) * per) + 1):
                    x = (i / cells * 2 - 1) * reach
                    z = (j / cells * 2 - 1) * reach
                    if math.hypot(x, z) > reach * 1.01:
                        continue
                    verts[(i, j)] = bm.verts.new((x, -z, land(x, z)))
            for i in range(ci * per, min(cells, (ci + 1) * per)):
                for j in range(cj * per, min(cells, (cj + 1) * per)):
                    q = [(i, j), (i, j + 1), (i + 1, j + 1), (i + 1, j)]  # wound so the faces look up
                    if all(k in verts for k in q):
                        bm.faces.new([verts[k] for k in q])
            if not bm.faces:
                bm.free()
                continue
            for v in [v for v in bm.verts if not v.link_faces]:
                bm.verts.remove(v)
            col = bm.loops.layers.color.new("Col")
            uv = bm.loops.layers.uv.new("UVMap")
            uv2 = bm.loops.layers.uv.new("UVMap2")
            bm.verts.index_update()
            for v in bm.verts:
                norms[v.index] = normal(v.co.x, -v.co.y)
            for f in bm.faces:
                for loop in f.loops:
                    v = loop.vert
                    x, z, h = v.co.x, -v.co.y, v.co.z
                    steep = 1.0 - norms[v.index][2]
                    n = noise(x * 1.7, z * 1.7, 11.0)
                    rock = smooth(0.3, 0.5, steep + 0.08 * n)
                    grass = smooth(1.6, 3.2, h + n * 0.8) * (1.0 - rock)
                    wet = 1.0 - smooth(-0.2, 0.7, h)
                    path = trodden(x, z) if trodden else 0.0
                    woods = (forest(x, z) if forest else 0.0) * (1.0 - rock)
                    shade = 0.94 + 0.06 * n  # light and dark patches (the colours come from the island's tints in the game)
                    warm = 0.03 * noise(x * 0.6, z * 0.6, 5.0)
                    loop[col] = (shade + warm, shade, shade - warm, woods)
                    loop[uv].uv = (grass, rock)
                    loop[uv2].uv = (wet, path)
            order = [norms[v.index] for v in bm.verts]
            piece = "%s_%d_%d" % (name, ci, cj) if chunks > 1 else name
            mesh = bpy.data.meshes.new(piece)
            bm.to_mesh(mesh)
            bm.free()
            for p in mesh.polygons:
                p.use_smooth = True
            mesh.normals_split_custom_set_from_vertices(order)
            mesh.color_attributes.active_color = mesh.color_attributes["Col"]
            obj = bpy.data.objects.new(piece, mesh)
            bpy.context.scene.collection.objects.link(obj)
            mesh.materials.append(bpy.data.materials.get("isle_ground") or bpy.data.materials.new("isle_ground"))
            objs.append(obj)
    return objs if chunks > 1 else objs[0]


class HeightGrid:
    """A height function sampled once on a square grid (island-local metres), read back by bilinear interpolation:
    big islands are painted, scattered and checked from this instead of calling the height function millions of times."""

    def __init__(self, fn, reach, step, note=""):
        self.reach, self.step = reach, step
        self.n = int(round(2 * reach / step)) + 1
        self.rows = []
        for j in range(self.n):
            z = -reach + j * step
            self.rows.append([fn(-reach + i * step, z) for i in range(self.n)])
        if note:
            print(note, self.n, "x", self.n)

    def at(self, x, z):
        fx = min(max((x + self.reach) / self.step, 0.0), self.n - 1.001)
        fz = min(max((z + self.reach) / self.step, 0.0), self.n - 1.001)
        i, j = int(fx), int(fz)
        tx, tz = fx - i, fz - j
        r0, r1 = self.rows[j], self.rows[j + 1]
        return (r0[i] * (1 - tx) + r0[i + 1] * tx) * (1 - tz) + (r1[i] * (1 - tx) + r1[i + 1] * tx) * tz

    def normal(self, i, j):
        n = self.n
        hx = (self.rows[j][min(i + 1, n - 1)] - self.rows[j][max(i - 1, 0)]) / (2 * self.step)
        hz = (self.rows[min(j + 1, n - 1)][i] - self.rows[max(j - 1, 0)][i]) / (2 * self.step)
        ln = math.sqrt(hx * hx + hz * hz + 1.0)
        return (-hx / ln, hz / ln, 1.0 / ln)  # Blender order (x, forward = -z, up)


class PathIndex:
    """Path segments bucketed on a coarse grid, so "how far to the nearest path" and road grading stay fast."""

    def __init__(self, paths, cell=16.0):
        self.cell = cell
        self.buckets = {}
        for line in paths:
            for a, b in zip(line, line[1:]):
                lo_i, hi_i = int(math.floor(min(a[0], b[0]) / cell)) - 1, int(math.floor(max(a[0], b[0]) / cell)) + 1
                lo_j, hi_j = int(math.floor(min(a[1], b[1]) / cell)) - 1, int(math.floor(max(a[1], b[1]) / cell)) + 1
                for i in range(lo_i, hi_i + 1):
                    for j in range(lo_j, hi_j + 1):
                        self.buckets.setdefault((i, j), []).append((a, b))

    def near(self, x, z):
        return self.buckets.get((int(math.floor(x / self.cell)), int(math.floor(z / self.cell))), ())


def seg_dist(x, z, a, b):
    dx, dz = b[0] - a[0], b[1] - a[1]
    ln = dx * dx + dz * dz
    t = 0.0 if ln == 0 else max(0.0, min(1.0, ((x - a[0]) * dx + (z - a[1]) * dz) / ln))
    return math.hypot(x - a[0] - dx * t, z - a[1] - dz * t), t


def smooth_path(pts, step=4.0, rounds=2):
    """A* zigzags on its 8-way grid: Chaikin-round the corners, then lay points every `step` m (ends kept)."""
    for _ in range(rounds):
        if len(pts) < 3:
            break
        out = [pts[0]]
        for a, b in zip(pts, pts[1:]):
            out.append((0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]))
            out.append((0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]))
        out.append(pts[-1])
        pts = out
    res = [pts[0]]
    carry = 0.0
    for a, b in zip(pts, pts[1:]):
        seg = math.hypot(b[0] - a[0], b[1] - a[1])
        d = step - carry
        while d < seg:
            t = d / seg
            res.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
            d += step
        carry = seg - (d - step)
    if math.hypot(res[-1][0] - pts[-1][0], res[-1][1] - pts[-1][1]) > 0.5:
        res.append(pts[-1])
    else:
        res[-1] = pts[-1]
    return [(round(x, 2), round(z, 2)) for x, z in res]


def paint(x, z, h, steep, path=0.0, woods=0.0):
    """One ground point's paint for game/isle_ground.gd: (vertex colour rgba, uv, uv2)."""
    n = noise(x * 1.7, z * 1.7, 11.0)
    rock = smooth(0.3, 0.5, steep + 0.08 * n) * (1.0 - smooth(0.2, 0.6, path))
    grass = smooth(1.6, 3.2, h + n * 0.8) * (1.0 - rock)
    wet = 1.0 - smooth(-0.2, 0.7, h)
    shade = 0.94 + 0.06 * n
    warm = 0.03 * noise(x * 0.6, z * 0.6, 5.0)
    return (shade + warm, shade, shade - warm, woods * (1.0 - rock)), (grass, rock), (wet, path)


def ground_chunks(name, grid, chunk, far_every, trodden=None, forest=None, keep=None):
    """The ground of a big island from a HeightGrid, cut into chunk x chunk metre pieces, each in two details: "<name>_i_j"
    at the grid's spacing and "<name>_i_j_far" at every `far_every`-th point (game/sea_islands.gd shows the near one
    close by and the far one beyond, and makes only near chunks solid). keep(x0, z0, x1, z1) -> False skips a chunk
    (open sea). Normals come from the whole grid, so chunk edges never show."""
    per = int(round(chunk / grid.step))
    count = (grid.n - 1) // per + (1 if (grid.n - 1) % per else 0)
    objs = []
    for ci in range(count):
        for cj in range(count):
            i0, j0 = ci * per, cj * per
            i1, j1 = min(i0 + per, grid.n - 1), min(j0 + per, grid.n - 1)
            x0, z0 = -grid.reach + i0 * grid.step, -grid.reach + j0 * grid.step
            x1, z1 = -grid.reach + i1 * grid.step, -grid.reach + j1 * grid.step
            if keep and not keep(x0, z0, x1, z1):
                continue
            for every, suffix in ((1, ""), (far_every, "_far")):
                objs.append(_chunk_mesh("%s_%d_%d%s" % (name, ci, cj, suffix), grid, i0, j0, i1, j1, every, trodden, forest))
    return objs


def _chunk_mesh(piece, grid, i0, j0, i1, j1, every, trodden, forest):
    bm = bmesh.new()
    ids = {}
    cols = list(range(i0, i1, every)) + [i1]
    rows = list(range(j0, j1, every)) + [j1]
    order = []
    for j in rows:
        for i in cols:
            x, z = -grid.reach + i * grid.step, -grid.reach + j * grid.step
            ids[(i, j)] = bm.verts.new((x, -z, grid.rows[j][i]))
            order.append(grid.normal(i, j))
    for a in range(len(cols) - 1):
        for b in range(len(rows) - 1):
            q = [(cols[a], rows[b]), (cols[a], rows[b + 1]), (cols[a + 1], rows[b + 1]), (cols[a + 1], rows[b])]
            bm.faces.new([ids[k] for k in q])
    bm.verts.index_update()
    col = bm.loops.layers.color.new("Col")
    uv = bm.loops.layers.uv.new("UVMap")
    uv2 = bm.loops.layers.uv.new("UVMap2")
    for f in bm.faces:
        for loop in f.loops:
            v = loop.vert
            x, z, h = v.co.x, -v.co.y, v.co.z
            steep = 1.0 - order[v.index][2]
            c, u1, u2 = paint(x, z, h, steep, trodden(x, z) if trodden else 0.0, forest(x, z) if forest else 0.0)
            loop[col] = c
            loop[uv].uv = u1
            loop[uv2].uv = u2
    mesh = bpy.data.meshes.new(piece)
    bm.to_mesh(mesh)
    bm.free()
    for p in mesh.polygons:
        p.use_smooth = True
    mesh.normals_split_custom_set_from_vertices(order)
    mesh.color_attributes.active_color = mesh.color_attributes["Col"]
    obj = bpy.data.objects.new(piece, mesh)
    bpy.context.scene.collection.objects.link(obj)
    mesh.materials.append(bpy.data.materials.get("isle_ground") or bpy.data.materials.new("isle_ground"))
    return obj


def water_strip(name, points, mat="water"):
    """A flat water surface along points [(x, y, z, half_width), ...] (island-local), UV v running with the flow so the
    game's water shader can stream it (rivers, the waterfall curtain is a strip that falls)."""
    bm = bmesh.new()
    rows = []
    for k, (x, y, z, w) in enumerate(points):
        nx, nz = points[min(k + 1, len(points) - 1)][0] - points[max(k - 1, 0)][0], points[min(k + 1, len(points) - 1)][2] - points[max(k - 1, 0)][2]
        ln = math.hypot(nx, nz) or 1.0
        sx, sz = -nz / ln, nx / ln
        rows.append((bm.verts.new((x + sx * w, -(z + sz * w), y)), bm.verts.new((x - sx * w, -(z - sz * w), y))))
    uv = bm.loops.layers.uv.new("UVMap")
    run = [0.0]
    for k in range(1, len(points)):
        a, b = points[k - 1], points[k]
        run.append(run[-1] + math.sqrt((b[0] - a[0]) ** 2 + (b[1] - a[1]) ** 2 + (b[2] - a[2]) ** 2))
    for k in range(len(rows) - 1):
        f = bm.faces.new((rows[k][0], rows[k][1], rows[k + 1][1], rows[k + 1][0]))
        for loop, (u, v) in zip(f.loops, ((0.0, run[k]), (1.0, run[k]), (1.0, run[k + 1]), (0.0, run[k + 1]))):
            loop[uv].uv = (u, v / 4.0)
    bm.normal_update()
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    mesh.materials.append(bpy.data.materials.get(mat) or bpy.data.materials.new(mat))
    return obj


def scatter(land, reach, seed, clear=None, density=1.0, green=1.0):
    """The props by rule: [model, x, y, z, yaw degrees, scale] in island-local metres. density 1 = the start island's;
    green thins the grass tufts, bushes and ferns on their own (big islands are mostly green)."""
    rnd = random.Random(seed)
    out = []
    for _ in range(int(52000 * density * (reach / 150.0) ** 2)):
        x, z = rnd.uniform(-reach, reach), rnd.uniform(-reach, reach)
        h = land(x, z)
        if h < -0.2 or (clear and clear(x, z)):
            continue
        s = slope(land, x, z)
        roll = rnd.random()
        if 1.0 < h < 6.5 and s < 0.35 and roll < 0.05:
            put(out, rnd, land, "palm_a" if rnd.random() < 0.6 else "palm_b", x, z, rnd.uniform(0.85, 1.2), 0.3)
        elif 0.3 < h < 1.8 and s < 0.25 and roll < 0.05:
            put(out, rnd, land, rnd.choice(["shells", "shells", "coconuts", "driftwood"]), x, z, rnd.uniform(0.8, 1.2), 0.0)
        elif h > 2.5 and s < 0.5 and roll < 0.09 * green:
            put(out, rnd, land, rnd.choice(["bush", "bush", "fern"]), x, z, rnd.uniform(0.7, 1.4), 0.1)
        elif h > 2.0 and s < 0.6 and roll < 0.42 * green:
            put(out, rnd, land, "grass_tuft", x, z, rnd.uniform(0.8, 1.5), 0.0)
        elif s > 0.45 and roll < 0.035:
            put(out, rnd, land, rnd.choice(["boulder_a", "boulder_b", "boulder_c"]), x, z, rnd.uniform(0.8, 1.6), 0.4)
        elif -0.2 < h < 1.0 and roll < 0.006:
            put(out, rnd, land, rnd.choice(["boulder_a", "boulder_c"]), x, z, rnd.uniform(0.6, 1.3), 0.3)
    return out


