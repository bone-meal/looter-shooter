def scatter_zones(land, reach, seed, zone, clear=None, density=1.0, bank=None):
    """The props of a zoned island. zone(x, z, h) -> "jungle" / "meadow" / "dune" / "rocky" / "beach"; bank(x, z) -> metres
    to the nearest fresh water (reeds grow within 4 m). Also everywhere: reefs and coral in the shallows, vines hanging
    from cliff tops (turned downhill), boulders at cliff feet."""
    rnd = random.Random(seed)
    out = []
    for _ in range(int(52000 * density * (reach / 150.0) ** 2)):
        x, z = rnd.uniform(-reach, reach), rnd.uniform(-reach, reach)
        if clear and clear(x, z):
            continue
        h = land(x, z)
        roll = rnd.random()
        if h < -0.6:  # the shallows: reefs and coral down to 7 m
            if h > -7.0 and roll < 0.012:
                put(out, rnd, land, rnd.choice(["reef_a", "reef_a", "reef_b"]), x, z, rnd.uniform(0.8, 1.4), 0.2)
            elif h > -6.0 and roll < 0.03:
                put(out, rnd, land, "coral", x, z, rnd.uniform(0.7, 1.4), 0.0)
            continue
        s = slope(land, x, z)
        if s > 1.1 and h > 4.0:  # a cliff face: vines hang from it, turned downhill
            if roll < 0.02:
                e = 1.0
                dx, dz = land(x + e, z) - land(x - e, z), land(x, z + e) - land(x, z - e)
                out.append(["vine", round(x, 2), round(h + 0.5, 2), round(z, 2), round(math.degrees(math.atan2(dx, dz)), 1), round(rnd.uniform(0.8, 1.3), 2)])
            continue
        if bank and h > -0.3 and bank(x, z) < 4.0:
            if roll < 0.25:
                put(out, rnd, land, "reeds", x, z, rnd.uniform(0.8, 1.3), 0.1)
            continue
        for rule in ZONE_RULES[zone(x, z, h)]:
            model, share, lo, hi, steep, s0, s1, sink = rule
            if roll < share * (density ** 0.0):
                if lo <= h <= hi and s <= steep:
                    put(out, rnd, land, rnd.choice(model) if isinstance(model, list) else model, x, z, rnd.uniform(s0, s1), sink)
                break
            roll -= share
    return out


def route(height, reach, start, goals, avoid=None, river=None, step=4.0, max_slope=0.42):
    """Paths generated over the ground (director: proper paths to every place, that can really be walked): from
    `start` to each goal in turn by A* on a grid of `step` m, never up or down more than `max_slope` per metre of the
    UNGRADED ground (height(x, z)), never into the sea, round `avoid(x, z)` (set pieces' footprints); crossing the
    river (river(x, z) -> metres to it) costs extra and leaves a bridge; a new path prefers ground an earlier path
    already uses, so the paths join into a network. Returns {goal name: [(x, z), ...]} (missing = no way found)."""
    import heapq
    n = int(2 * reach / step) + 1
    def xz(i, j):
        return (-reach + i * step, -reach + j * step)
    hs = {}
    def h_at(i, j):
        if (i, j) not in hs:
            x, z = xz(i, j)
            hs[(i, j)] = height(x, z)
        return hs[(i, j)]
    def cell(p):
        return (int(round((p[0] + reach) / step)), int(round((p[1] + reach) / step)))
    used = set()
    out = {}
    for name, goal in goals.items():
        a, b = cell(start), cell(goal)
        best = {a: 0.0}
        came = {}
        todo = [(0.0, a)]
        found = False
        while todo:
            _f, cur = heapq.heappop(todo)
            if cur == b:
                found = True
                break
            g = best[cur]
            ci, cj = cur
            hc = h_at(ci, cj)
            for di in (-1, 0, 1):
                for dj in (-1, 0, 1):
                    if di == 0 and dj == 0:
                        continue
                    nb = (ci + di, cj + dj)
                    if not (0 <= nb[0] < n and 0 <= nb[1] < n):
                        continue
                    x, z = xz(*nb)
                    hn = h_at(*nb)
                    dist = step * math.hypot(di, dj)
                    rise = abs(hn - hc) / dist
                    if rise > max_slope or (nb != b and (hn < 0.15 or (avoid and avoid(x, z)))):
                        continue
                    cost = dist * (1.0 + 6.0 * rise * rise) * (0.4 if nb in used else 1.0)
                    if river and river(x, z) < 3.0 and not (river(*xz(ci, cj)) < 3.0):
                        cost += 60.0  # a bridge
                    ng = g + cost
                    if ng < best.get(nb, 1e18):
                        best[nb] = ng
                        came[nb] = cur
                        heapq.heappush(todo, (ng + 0.9 * math.hypot(nb[0] - b[0], nb[1] - b[1]) * step, nb))
        if not found:
            continue
        cells = [b]
        while cells[-1] != a:
            cells.append(came[cells[-1]])
        cells.reverse()
        used.update(cells)
        pts = [xz(*c) for c in cells]
        pts[0], pts[-1] = start, goal
        out[name] = pts  # a point every 4 m: each step keeps the slope limit
    return out


def put(out, rnd, land, model, x, z, scale=1.0, sink=0.05):
    out.append([model, round(x, 2), round(land(x, z) - sink * scale, 2), round(z, 2), round(rnd.uniform(0, 360), 1), round(scale, 2)])


def save(name, obj, props, source, places=None, water=None, routes=None):
    """obj = the ground (one object or a list of chunks); places = set pieces [model, x, y, z, yaw, scale];
    water = water surface objects (written to <name>_water.glb); routes = start / pois / paths for the walk check."""
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PROPS_OUT, exist_ok=True)
    objs = obj if isinstance(obj, list) else [obj]
    bpy.ops.object.select_all(action="DESELECT")
    for o in objs:
        o.select_set(True)
    bpy.ops.export_scene.gltf(filepath=os.path.join(OUT, name + ".glb"), use_selection=True, export_format="GLB")
    if water:
        bpy.ops.object.select_all(action="DESELECT")
        for o in water:
            o.select_set(True)
        bpy.ops.export_scene.gltf(filepath=os.path.join(OUT, name + "_water.glb"), use_selection=True, export_format="GLB")
    about = "Island props (%s writes this): [model, x, y, z, yaw degrees, scale] in island-local metres. solid = collision radius per model (0 = a wall: a box). places = set pieces (assets/models/sea/places/<model>.gltf), solid as modelled." % source
    data = {"_about": about, "props": props, "solid": SOLID}
    if places:
        data["places"] = places
    if routes:  # start, pois {name: [x, z]}, paths [[[x, z], ...], ...]: the walk check (game: !isle walk)
        data.update(routes)
    with open(os.path.join(PROPS_OUT, name + ".json"), "w") as f:
        json.dump(data, f)
    counts = {}
    for p in props:
        counts[p[0]] = counts.get(p[0], 0) + 1
    print(name, sum(len(o.data.vertices) for o in objs), "verts", len(props), "props", len(places or []), "places", counts)
