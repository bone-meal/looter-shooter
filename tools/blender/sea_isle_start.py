def ang_d(a, b):
    return math.atan2(math.sin(a - b), math.cos(a - b))


def bump(ang, at, width):
    return math.exp(-(ang_d(ang, at) / width) ** 2)


def polar(ang, r):
    return (r * math.cos(ang), r * math.sin(ang))


def shore_radius(ang):
    r = R0 * (1.0 + 0.07 * math.sin(3 * ang + 1.0) + 0.045 * math.sin(5 * ang + 2.2) + 0.025 * math.sin(9 * ang + 0.4) + 0.015 * math.sin(17 * ang + 1.3))
    r += 70.0 * S * bump(ang, math.pi, 0.17)  # the west headland
    r += 48.0 * S * bump(ang, 2.25, 0.05)  # a sand spit to the south-west
    r += 42.0 * S * bump(ang, -0.4, 0.1)  # the lighthouse point
    r -= 34.0 * S * bump(ang, -2.35, 0.09)  # a small cove in the north-west
    r -= 22.0 * S * bump(ang, 0.62, 0.06)  # the lagoon channel's mouth
    r += 55.0 * bump(ang, 0.1, 0.35)  # the town's shoulder of land round the harbour
    return r


def northness(ang):
    return max(0.0, -math.sin(ang)) ** 1.4 * (1.0 - bump(ang, -0.4, 0.25)) * (1.0 - bump(ang, 0.0, 0.5))  # no cliffs at the town


def gauss(x, z, cx, cz, sx, sz):
    return math.exp(-(((x - cx) / sx) ** 2 + ((z - cz) / sz) ** 2))


LIGHTHOUSE = polar(-0.4, shore_radius(-0.4) - 50.0)
WRECK = polar(1.75, shore_radius(1.75) - 30.0)
LIFTS = [  # flat pads for the places: x, z, radius, height (None = the ground's own height there)
    (RUINS[0], RUINS[1], 13.0, None), (CAVE[0], CAVE[1], 11.0, None), (LIGHTHOUSE[0], LIGHTHOUSE[1], 10.0, None),
    (CAMP[0], CAMP[1], 9.0, None),
]


_BEDS = []


def beds():
    """The river's bed heights from the land it runs through (always downhill, under the ground above the fall)."""
    if not _BEDS:
        prev = 1e9
        for k, (x, z, most) in enumerate(RIVER):
            b = min(most, inland(x, z) - (3.0 if k <= FALL else 1.5), prev - (0.5 if k != FALL + 1 else 12.0))
            _BEDS.append((x, z, b))
            prev = b
    return _BEDS


def river_at(x, z):
    """(distance to the river line, bed height there)."""
    best, bed = 1e9, 0.0
    line = beds()
    for k in range(len(line) - 1):
        a, b = line[k], line[k + 1]
        d, t = seg_dist(x, z, a, b)
        if d < best:
            best = d
            bed = a[2] + (b[2] - a[2]) * (smooth(0.25, 0.55, t) if k == FALL else t)
    return best, bed


def terrace_w(x, z):
    return smooth(0.25, 0.55, gauss(x, z, -120.0 * S, -10.0 * S, 55.0 * S, 40.0 * S))


def town_w(x, z):
    cx, cz, ax, az = TOWN_SITE
    d = math.sqrt(((x - cx) / ax) ** 2 + ((z - cz) / az) ** 2)
    return 1.0 - smooth(0.85, 1.25, d)


def inland(x, z):
    peak = 160.0 * gauss(x, z, NW_PEAK[0], NW_PEAK[1], 68.0 * S, 58.0 * S) + 10.0 * noise(x, z, 3.0) * gauss(x, z, NW_PEAK[0], NW_PEAK[1], 50.0 * S, 45.0 * S)
    east = 90.0 * gauss(x, z, E_PEAK[0], E_PEAK[1], 110.0, 95.0)
    ridge = 45.0 * gauss(x, z, 10.0 * S, -95.0 * S, 120.0 * S, 40.0 * S)
    south = 22.0 * gauss(x, z, -90.0 * S, 110.0 * S, 90.0 * S, 70.0 * S)
    base = 7.0 + 4.0 * noise(x * 0.6, z * 0.6, 3.0) + 1.5 * noise(x * 2.5, z * 2.5, 21.0)
    h = base + max(peak, east, ridge, south) + 0.25 * min(peak + east + ridge, 60.0)
    ex, ez, dx, dz = ESCARP  # the escarpment: the land upstream of the waterfall stands 22 m higher, over a rock step
    along = (x - ex) * dz - (z - ez) * dx
    up = -((x - ex) * dx + (z - ez) * dz) + 6.0 * noise(x, z, 13.0) * smooth(15.0, 50.0, abs(along))
    h += 22.0 * smooth(0.0, 6.0, up) * math.exp(-(along / (120.0 * S)) ** 2)
    w = terrace_w(x, z)
    if w > 0.0:  # terraces on the peak's south flank: 3 m steps
        stepped = math.floor(h / 3.0) * 3.0 + 3.0 * smooth(0.85, 1.0, (h / 3.0) % 1.0)
        h = h * (1.0 - w) + stepped * w
    tw = town_w(x, z)
    if tw > 0.0:  # the town's ground: a gentle slope rising west from the harbour, a little terraced by nature
        cx, cz, ax, az = TOWN_SITE
        town = 3.0 + max(0.0, (HARBOUR[0] - HARBOUR[2] * 0.6 - x)) * 0.09 + 1.2 * noise(x * 1.5, z * 1.5, 31.0)
        h = h * (1.0 - tw) + town * tw
    return h


_GRADING = True
_PATHS = []
_MISSING = []
_INDEX = []
_ROAD = {}


def land(x, z):
    """Ground height (m above sea level) at island-local x, z."""
    ang = math.atan2(z, x)
    north = northness(ang)
    r = math.hypot(x, z) + north * 10.0 * noise(x * 0.5, z * 0.5, 4.0) + 9.0 * noise(x * 0.8, z * 0.8, 8.0)
    R = shore_radius(ang)
    t = (R - r) / R
    west = bump(ang, math.pi, 0.25)
    if t < 0.0:  # the shelf: steep under the cliffs, shallow reefs off the west, deep off the harbour
        east = max(0.0, math.cos(ang)) * (1.0 - bump(ang, -0.4, 0.2))
        h = -0.5 + t * R * (0.1 + 0.4 * north + 0.18 * east - 0.05 * west)
        h += west * 1.2 * noise(x * 1.5, z * 1.5, 6.0)
        h = max(h, -30.0)
    else:
        beach_w = 0.05 * (1.0 - north) + 0.004
        u = min(t / beach_w, 1.0)
        beach = 0.15 + 2.2 * u * u
        rise = smooth(beach_w, beach_w + 0.07 * (1.0 - north) + 0.015, t)
        dune = bump(ang, 1.5, 0.45) * 3.5 * max(0.0, math.sin(r * 0.06 + noise(x, z, 2.0) * 2.0)) * (1.0 - smooth(beach_w * 0.8, beach_w * 1.6, t)) * smooth(0.0, beach_w * 0.4, t)
        land_h = inland(x, z)
        h = beach * (1.0 - rise) + land_h * rise + dune
        if north > 0.2:  # cliffs: a plateau 30-45 m up runs right to the edge
            sheer = smooth(0.2, 0.55, north)
            top = max(land_h, (36.0 + 12.0 * noise(x * 0.5, z * 0.5, 9.0) + 5.0 * noise(x, z, 12.0)) * (1.0 - smooth(0.1, 0.3, t)))
            h = h * (1.0 - sheer) + top * smooth(0.0, 0.02, t) * sheer
        h += west * 4.0 * noise(x, z, 7.0) * smooth(0.0, 0.04, t)  # a broken rocky headland
    # the lagoon (open to the sea by a channel to the south-east)
    lx, lz, lr = LAGOON
    dl = math.hypot(x - lx, z - lz)
    mouth, _ = seg_dist(x, z, (lx, lz), (lx + 170.0 * S * math.cos(0.62), lz + 170.0 * S * math.sin(0.62)))
    dl = min(dl, lr * 0.5 + mouth * 1.6)
    if dl < lr * 1.6:
        water = -4.0 * (1.0 - smooth(lr * 0.4, lr, dl))
        bank = 0.3 + 1.6 * smooth(lr, lr * 1.5, dl)
        h = min(h, water if dl < lr else bank * (1.0 - smooth(lr, lr * 1.6, dl)) + h * smooth(lr, lr * 1.6, dl))
    # the harbour (open to the east) and the shipyard's flat yard + slipway bed on its west bank
    cx, cz, cr = HARBOUR
    dc = math.hypot(x - cx, z - cz) if x < cx else abs(z - cz) * 0.9
    if dc < cr * 1.5:
        water = -8.0 * (1.0 - smooth(cr * 0.5, cr, dc)) - 0.1 * max(0.0, x - cx)
        bank = 0.5 + 1.5 * smooth(cr * 0.88, cr * 1.3, dc)
        shore = smooth(cr * 0.88, cr * 1.5, dc)
        h = min(h, water) if dc < cr * 0.88 else min(h, bank * (1.0 - shore) + h * shore)
    w = (1.0 - smooth(7.0, 13.0, abs(z - SLIP[1]))) * smooth(SLIP[0] - 24.0, SLIP[0] - 16.0, x)
    if w > 0.0:
        bed_h = 0.35 if x < SLIP[0] - 7.0 else 0.35 - (x - SLIP[0] + 7.0) * 0.13
        h = min(h, h * (1.0 - w) + bed_h * w)
    for px, pz, pr, ph in LIFTS:  # flat pads for the places
        dp = math.hypot(x - px, z - pz)
        if dp < pr * 1.8:
            target = ph if ph is not None else inland(px, pz)
            k = 1.0 - smooth(pr, pr * 1.8, dp)
            h = h * (1.0 - k) + target * k
    h = graded(x, z, h)
    # the river valley, its channel and the waterfall; where a road crosses only the channel is cut (a bridge spans it)
    d, bed = river_at(x, z)
    if d < 60.0 and h > bed - 3.0:
        channel = bed - 1.2 + 0.05 * d * d
        if _GRADING and path_off(x, z) < 12.0:
            h = min(h, channel * (1.0 - smooth(2.5, 4.0, d)) + h * smooth(2.5, 4.0, d))
        else:
            valley = bed + 1.0 + max(0.0, d - 6.0) * 0.45 + max(0.0, d - 25.0) * 0.5
            h = min(h, valley if d > 4.0 else min(valley, channel))
    return h


def raw_height(x, z):
    global _GRADING
    _GRADING = False
    h = land(x, z)
    _GRADING = True
    return h


def places_list():
    """The places paths are generated to (each path ends at the place's doorstep): name -> (x, z)."""
    return {
        "town": TOWN, "shipyard": (SLIP[0] - 12.0, SLIP[1]), "lighthouse": polar(-0.4, shore_radius(-0.4) - 62.0),
        "waterfall_top": (RIVER[FALL][0] + 10.0, RIVER[FALL][1] - 9.0), "waterfall_foot": (RIVER[FALL + 1][0] + 16.0, RIVER[FALL + 1][1] + 2.0),
        "ruins": (RUINS[0], RUINS[1] + 14.0), "cave": (CAVE[0] + 4.0, CAVE[1] + 13.0), "jetty": (LAGOON[0] + 20.0, LAGOON[1] - LAGOON[2] - 6.0),
        "wreck": (WRECK[0] + 8.0, WRECK[1] - 18.0), "camp": (CAMP[0] + 8.0, CAMP[1] + 6.0), "tide_pools": polar(math.pi, shore_radius(math.pi) - 40.0),
    }


def paths():
    """The generated, smoothed paths (cached): A* over the ungraded ground from the plaza to every place."""
    if not _PATHS:
        global _GRADING
        _GRADING = False
        try:
            raw = kit.HeightGrid(land, REACH, 4.0, "raw grid")
            pois = places_list()
            found = kit.route(raw.at, REACH, pois[START], {k: v for k, v in pois.items() if k != START},
                avoid=lambda x, z: any(math.hypot(x - ax, z - az) < ar for ax, az, ar in AVOID), river=lambda x, z: river_at(x, z)[0])
            for line in found.values():
                pts, fixed = _straight_over_river(kit.smooth_path(line), raw)
                hs = [fixed.get(p, raw.at(p[0], p[1])) for p in pts]
                for _ in range(60):  # the road's own profile: steps a smoothed point lands on (terraces) are eased out
                    for i in range(1, len(pts) - 1):
                        if pts[i] in fixed:
                            continue
                        d = max(math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]), 0.5)
                        if max(abs(hs[i] - hs[i - 1]), abs(hs[i + 1] - hs[i])) / d > 0.55:
                            hs[i] = (hs[i - 1] + hs[i + 1]) * 0.5
                for pt, h in zip(pts, hs):
                    _ROAD[pt] = h
                _PATHS.append(pts)
        finally:
            _GRADING = True
        _MISSING.extend(k for k in places_list() if k != START and k not in found)
        _INDEX.append(kit.PathIndex(_PATHS))
    return _PATHS


_BRIDGES = []  # (x, z, axis x, axis z, height at -BRIDGE_HALF, height at +BRIDGE_HALF): one per river crossing
BRIDGE_HALF = 7.0


def _straight_over_river(pts, raw):
    """Where a path crosses the river it runs STRAIGHT over it, square to the river, 9 m each side (the footbridge's
    line: its deck ends meet the road exactly); paths crossing near an earlier crossing share its bridge. Returns the
    new points and the heights fixed on the straight part {point: height}."""
    line = beds()
    fixed = {}
    for n in range(len(pts) - 1):
        a, b = pts[n], pts[n + 1]
        for k in range(len(line) - 1):
            if k == FALL:
                continue
            p, q = line[k], line[k + 1]
            d1 = (b[0] - a[0], b[1] - a[1])
            d2 = (q[0] - p[0], q[1] - p[1])
            den = d1[0] * d2[1] - d1[1] * d2[0]
            if abs(den) < 1e-6:
                continue
            t = ((p[0] - a[0]) * d2[1] - (p[1] - a[1]) * d2[0]) / den
            u = ((p[0] - a[0]) * d1[1] - (p[1] - a[1]) * d1[0]) / den
            if not (0.0 <= t <= 1.0 and 0.0 <= u <= 1.0):
                continue
            cx, cz = a[0] + d1[0] * t, a[1] + d1[1] * t
            shared = [g for g in _BRIDGES if math.hypot(g[0] - cx, g[1] - cz) < 15.0]
            if shared:
                cx, cz, ax, az, hb, ha = shared[0]
            else:
                ln = math.hypot(d2[0], d2[1])
                ax, az = -d2[1] / ln, d2[0] / ln  # square to the river
                if ax * d1[0] + az * d1[1] < 0.0:
                    ax, az = -ax, -az
                hb, ha = raw.at(cx - ax * 9.0, cz - az * 9.0), raw.at(cx + ax * 9.0, cz + az * 9.0)
                _BRIDGES.append((cx, cz, ax, az, hb + (ha - hb) * (2.0 / 18.0), hb + (ha - hb) * (16.0 / 18.0)))
            if ax * d1[0] + az * d1[1] < 0.0:  # this path runs the other way over a shared bridge
                ax, az, hb, ha = -ax, -az, ha, hb
                g = [g for g in _BRIDGES if math.hypot(g[0] - cx, g[1] - cz) < 15.0][0]
                hb9, ha9 = g[5] + (g[5] - g[4]) / 7.0, g[4] - (g[5] - g[4]) / 7.0
            else:
                g = [g for g in _BRIDGES if math.hypot(g[0] - cx, g[1] - cz) < 15.0][0]
                hb9, ha9 = g[4] - (g[5] - g[4]) / 7.0, g[5] + (g[5] - g[4]) / 7.0
            run = [0.0]
            for i in range(1, len(pts)):
                run.append(run[-1] + math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]))
            at = run[n] + math.hypot(cx - a[0], cz - a[1])
            before = [pt for pt, r in zip(pts, run) if r < at - 11.0]
            after = [pt for pt, r in zip(pts, run) if r > at + 11.0]
            mid = []
            for s_ in (-9.0, -4.5, 0.0, 4.5, 9.0):
                pt = (round(cx + ax * s_, 2), round(cz + az * s_, 2))
                fixed[pt] = hb9 + (ha9 - hb9) * (s_ + 9.0) / 18.0
                mid.append(pt)
            more, more_fixed = _straight_over_river(after, raw) if after else ([], {})
            fixed.update(more_fixed)
            return before + mid + more, fixed
    return pts, fixed


def path_off(x, z):
    paths()
    best = 99.0
    for a, b in _INDEX[0].near(x, z):
        best = min(best, seg_dist(x, z, a, b)[0])
    return best


def graded(x, z, h):
    """Paths as roads: within 4 m of a path the ground is the line between its points' heights (cut or fill), blended
    out to 10 m; nearby roads count by distance, so joins are smooth."""
    if not _GRADING:
        return h
    paths()
    total, weight, most = 0.0, 0.0, 0.0
    for a, b in _INDEX[0].near(x, z):
        d, t = seg_dist(x, z, a, b)
        if d < 10.0:
            w = 1.0 - smooth(4.0, 10.0, d)
            w2 = w / (0.3 + d)
            total += (_ROAD[a] + (_ROAD[b] - _ROAD[a]) * t) * w2
            weight += w2
            most = max(most, w)
    if weight <= 0.0:
        return h
    return h * (1.0 - most) + (total / weight) * most


def crossings():
    """The footbridges: (x, z, yaw degrees along the bridge, deck height at its back end, at its front end)."""
    paths()
    return [(x, z, math.degrees(math.atan2(-ax, -az)), hb, ha) for x, z, ax, az, hb, ha in _BRIDGES]


def route_check(height):
    """Build-time check of the paths (director: every place reachable by a path that can really be walked), on the
    ground as built (height = the final height grid): the network joins the plaza, every place lies at a path, and
    along each path the road is above the sea and walkable along AND across (rise <= 0.75 per metre along the middle,
    0.85 along lines 1.5 m to each side, 0.75 across; the game's floor limit is 45 degrees = 1.0). Returns the problems (empty = fine)."""
    problems = ["%s: no walkable way found from %s" % (k, START) for k in _MISSING]
    pois = places_list()
    pts = [pt for line in paths() for pt in line]
    links = {pt: set() for pt in pts}
    for line in paths():
        for a, b in zip(line, line[1:]):
            links[a].add(b)
            links[b].add(a)
    grid = {}
    for p in pts:
        grid.setdefault((int(p[0] // 4), int(p[1] // 4)), []).append(p)
    for a in pts:  # path points lying on another path join it
        gi, gj = int(a[0] // 4), int(a[1] // 4)
        for di in (-1, 0, 1):
            for dj in (-1, 0, 1):
                for b in grid.get((gi + di, gj + dj), ()):
                    if a != b and math.hypot(a[0] - b[0], a[1] - b[1]) < 3.0:
                        links[a].add(b)
    start = min(pts, key=lambda q: math.hypot(q[0] - pois[START][0], q[1] - pois[START][1]))
    seen, todo = set(), [start]
    while todo:
        cur = todo.pop()
        if cur in seen:
            continue
        seen.add(cur)
        todo.extend(links[cur])
    for name, at in pois.items():
        near = min(pts, key=lambda q: math.hypot(q[0] - at[0], q[1] - at[1]))
        if math.hypot(near[0] - at[0], near[1] - at[1]) > 12.0:
            problems.append("%s: %.0f m from any path" % (name, math.hypot(near[0] - at[0], near[1] - at[1])))
        elif near not in seen:
            problems.append("%s: its path does not join %s" % (name, START))
    bridges = crossings()
    for x, z, yaw, _back, _ahead in bridges:  # the road must run level onto a footbridge's deck ends (no step)
        fx, fz = -math.sin(math.radians(yaw)), -math.cos(math.radians(yaw))
        for sign in (-1.0, 1.0):
            end = height(x + fx * BRIDGE_HALF * sign, z + fz * BRIDGE_HALF * sign)
            before = height(x + fx * (BRIDGE_HALF + 1.5) * sign, z + fz * (BRIDGE_HALF + 1.5) * sign)
            if abs(end - before) / 1.5 > 0.6:
                problems.append("bridge at (%.0f, %.0f): the road meets its deck at %.2f rise per metre" % (x, z, abs(end - before) / 1.5))
    for line in paths():
        for a, b in zip(line, line[1:]):
            ln = math.hypot(b[0] - a[0], b[1] - a[1])
            if ln < 0.01:
                continue
            fx, fz = (b[0] - a[0]) / ln, (b[1] - a[1]) / ln
            n = max(1, int(ln / 0.5))
            for side in (-1.5, 0.0, 1.5):
                prev = height(a[0] - fz * side, a[1] + fx * side)
                worst, low = 0.0, 99.0
                for k in range(1, n + 1):
                    x = a[0] + (b[0] - a[0]) * k / n - fz * side
                    z = a[1] + (b[1] - a[1]) * k / n + fx * side
                    h = height(x, z)
                    if any(math.hypot(x - c[0], z - c[1]) < BRIDGE_HALF for c in bridges):  # on a bridge: its deck carries the path
                        prev = h
                        continue
                    worst = max(worst, abs(h - prev) / (ln / n))
                    low = min(low, h)
                    prev = h
                if worst > (0.75 if side == 0.0 else 0.85):  # the road's edges may be a little steeper than its middle
                    problems.append("path at (%.0f, %.0f): %.2f rise per metre (%+.1f m off the middle)" % (a[0], a[1], worst, side))
                if side == 0.0 and low < 0.1:
                    problems.append("path at (%.0f, %.0f): under the sea (%.1f m)" % (a[0], a[1], low))
                across = abs(height(a[0] - fz * 1.5, a[1] + fx * 1.5) - height(a[0] + fz * 1.5, a[1] - fx * 1.5)) / 3.0
                if side == 0.0 and across > 0.75 and not any(math.hypot(a[0] - c[0], a[1] - c[1]) < BRIDGE_HALF for c in bridges):
                    problems.append("path at (%.0f, %.0f): %.2f across" % (a[0], a[1], across))
    return list(dict.fromkeys(problems))


def zone(x, z, h):
    """The plant zone at a spot (director: plant variety + zones; the town's site is kept open)."""
    ang = math.atan2(z, x)
    r = math.hypot(x, z)
    R = shore_radius(ang)
    if town_w(x, z) > 0.5:
        return "town"
    if h > 110.0 or bump(ang, math.pi, 0.22) * smooth(0.85, 0.96, r / R) > 0.4:
        return "rocky"
    if r > R * 0.82 and h < 14.0 and bump(ang, 1.5, 0.6) > 0.35:
        return "dune"
    if h < 4.5 and r > R * 0.88:
        return "beach"
    wobble = 0.18 * noise(x * 0.6, z * 0.6, 17.0)
    if gauss(x, z, E_PEAK[0], E_PEAK[1], 160.0, 140.0) + wobble > 0.35 or terrace_w(x, z) > 0.4 or northness(ang) + wobble > 0.4:
        return "meadow"
    return "jungle"


def blocks(p):
    r = kit.SOLID.get(p[0])
    if r is None:
        return False
    return path_off(p[1], p[3]) < (r if r > 0 else 2.0) * p[5] + 0.6


def place(final):
    """The kit's zoned props plus this island's hand-placed set pieces. `final` = the ground as built."""
    def clear(x, z):  # the shipyard's ground, roads, the places' pads, the river
        if (SLIP[0] - 16.0 < x < SLIP[0] + 20.0 and abs(z - SLIP[1]) < 10.0) or path_off(x, z) < 5.0:
            return True
        for px, pz, pr, _ph in LIFTS:
            if math.hypot(x - px, z - pz) < pr:
                return True
        return river_at(x, z)[0] < 2.0
    props = kit.scatter_zones(final.at, REACH, 7, zone, clear, density=0.5, bank=lambda x, z: river_at(x, z)[0] - 3.0)
    rnd = random.Random(8)
    for ang in (-1.15, -1.45, -1.75, -2.05, -2.6, -1.3, -1.9):  # sea stacks off the north cliffs
        x, z = polar(ang, shore_radius(ang) + rnd.uniform(25, 70))
        props.append(["sea_stack", round(x, 2), 0.0, round(z, 2), round(rnd.uniform(0, 360), 1), round(rnd.uniform(1.0, 1.6), 2)])
    for k in range(24):  # the west headland's tide-washed boulders and tors
        ang = math.pi + rnd.uniform(-0.3, 0.3)
        x, z = polar(ang, shore_radius(ang) + rnd.uniform(-45, 20))
        kit.put(props, rnd, final.at, "boulder_b" if k % 3 else "outcrop_tor", x, z, rnd.uniform(1.0, 2.2), 0.6)
    for ang, rr in ((-1.9, 0.62), (-0.9, 0.7), (2.8, 0.55), (-2.4, 0.5), (1.2, 0.45), (2.2, 0.7)):  # crags inland
        x, z = polar(ang, rr * shore_radius(ang))
        kit.put(props, rnd, final.at, rnd.choice(["outcrop_slabs", "outcrop_spires"]), x, z, rnd.uniform(1.2, 2.0), 0.8)
    for k in range(8):  # ruined walls on the terraces
        kit.put(props, rnd, final.at, "ruin_wall", RUINS[0] + rnd.uniform(-60, 60), RUINS[1] + rnd.uniform(25, 90), rnd.uniform(0.8, 1.2), 0.1)
    props = [p for p in props if not blocks(p)]  # nothing solid stands on a road
    places = []
    def put_place(model, x, z, yaw, y=None, scale=1.0):
        places.append([model, round(x, 2), round(final.at(x, z) if y is None else y, 2), round(z, 2), yaw, scale])
    put_place("sea_arch", *polar(-1.0, shore_radius(-1.0) + 70.0), 30.0, 0.0)
    put_place("ruins_temple", RUINS[0], RUINS[1], 180.0)
    put_place("cave", CAVE[0], CAVE[1], 200.0)
    put_place("lighthouse", LIGHTHOUSE[0], LIGHTHOUSE[1], 230.0)
    put_place("camp", CAMP[0], CAMP[1], 290.0)
    put_place("wreck", WRECK[0], WRECK[1], 25.0)
    jx, jz = LAGOON[0] + 20.0, LAGOON[1] - LAGOON[2] + 4.0
    while final.at(jx, jz) > 1.4:  # the jetty's land end where the shore is about 1.3 m high
        jz += 1.0
    put_place("jetty", jx, jz, 180.0, 0.0)
    WALK_INTO["jetty"] = (jx, jz + 24.0)
    for x, z, yaw, back, ahead in crossings():  # footbridges on the straight road over the river, ends at road height
        fx, fz = -math.sin(math.radians(yaw)), -math.cos(math.radians(yaw))
        back, ahead = final.at(x - fx * BRIDGE_HALF, z - fz * BRIDGE_HALF), final.at(x + fx * BRIDGE_HALF, z + fz * BRIDGE_HALF)
        places.append(["bridge", round(x, 2), round((back + ahead) * 0.5, 2), round(z, 2), round(yaw, 1), 1.0, round(math.degrees(math.atan2(ahead - back, 2.0 * BRIDGE_HALF)), 1)])
    for k in range(3):  # tide pools on the headland's rock shelf
        x, z = polar(math.pi + (k - 1) * 0.05, shore_radius(math.pi + (k - 1) * 0.05) - 8.0)
        put_place("tide_pool", x, z, round(rnd.uniform(0, 360), 1), round(max(final.at(x, z), 0.15), 2))
    return props, places


def water():
    """The river surface from the spring to the waterfall lip, the falling curtain, the river below to the lagoon."""
    upper, lower = [], []
    line = beds()
    for k in range(len(line) - 1):
        a, b = line[k], line[k + 1]
        if k == FALL:
            continue
        n = max(2, int(math.hypot(b[0] - a[0], b[1] - a[1]) / 3.0))
        last = k == FALL - 1 or k == len(line) - 2
        for j in range(n + (1 if last else 0)):
            t = j / n
            x, z = a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t
            y = max(a[2] + (b[2] - a[2]) * t - 0.4, 0.1)
            (upper if k < FALL else lower).append((x, y, z, 4.0 if k < FALL else 5.0))
    lip, foot = line[FALL], line[FALL + 1]
    fall = []
    for j in range(11):
        t = j / 10
        x = lip[0] + (foot[0] - lip[0]) * (0.25 + 0.3 * t)
        z = lip[1] + (foot[1] - lip[1]) * (0.25 + 0.3 * t)
        fall.append((x, lip[2] - 0.4 - (lip[2] - foot[2]) * t * t, z, 4.5))
    return [kit.water_strip("river_upper", upper), kit.water_strip("waterfall", fall, "waterfall"), kit.water_strip("river_lower", lower)]


